import * as fs from 'fs';
import * as path from 'path';
import * as dotenv from 'dotenv';
import { GeneratorAgent } from '../src/agents/GeneratorAgent';
import { createProvider } from '../src/agents/providers/createProvider';
import { StepParser } from '../src/utils/StepParser';

dotenv.config();

/**
 * generate.ts — CLI script to generate missing step definitions for a .feature file.
 *
 * Usage:
 *   npm run generate                                          (uses default feature file)
 *   npm run generate -- src/features/todo-editing.feature    (specify a file)
 *
 * What it does:
 *   1. Extracts all steps from the .feature file
 *   2. Checks which ones already have a step definition
 *   3. Reports the match — skips existing, generates only missing
 *   4. Saves new step definitions to src/steps/<feature-name>.steps.ts
 */
async function main(): Promise<void> {
  const featurePath = process.argv[2] ?? 'src/features/todo-editing.feature';

  if (!fs.existsSync(featurePath)) {
    console.error(`[Generator] File not found: ${featurePath}`);
    console.error(`[Generator] Run "npm run plan" first to generate the feature file.`);
    process.exit(1);
  }

  const stepsDir = path.join('src', 'steps');

  // ── Step 1: Extract all steps from the feature file ──────────────────────
  const featureSteps = StepParser.extractStepsFromFeature(featurePath);
  console.log(`[Generator] Found ${featureSteps.length} unique step(s) in: ${featurePath}`);

  // ── Step 2: Load existing step patterns ──────────────────────────────────
  const existingPatterns = StepParser.extractPatternsFromDir(stepsDir);

  // ── Step 3: Classify each step ───────────────────────────────────────────
  const existingSteps: string[] = [];
  const missingSteps: string[] = [];

  for (const step of featureSteps) {
    if (StepParser.findMissingSteps([step], existingPatterns).length === 0) {
      existingSteps.push(step);
    } else {
      missingSteps.push(step);
    }
  }

  console.log(`\n[Generator] Step analysis:`);
  existingSteps.forEach((s) => console.log(`  [SKIP - already exists] ${s}`));
  missingSteps.forEach((s) => console.log(`  [GENERATE]              ${s}`));

  if (missingSteps.length === 0) {
    console.log('\n[Generator] All steps already implemented. Nothing to generate.');
    return;
  }

  // ── Step 4: Generate missing step definitions ─────────────────────────────
  const pomContent = fs.readFileSync(path.join('src', 'pages', 'TodoPage.ts'), 'utf-8');
  const provider = createProvider();
  const generator = new GeneratorAgent(provider);

  const result = await generator.generateSteps({ missingSteps, pomContent });

  // ── Step 5: Save generated steps ─────────────────────────────────────────
  const baseName = path.basename(featurePath, '.feature');
  const outputPath = path.join(stepsDir, `${baseName}.steps.ts`);

  const header = `// AUTO-GENERATED by GeneratorAgent — review before committing\n// Source: ${featurePath}\n\n`;
  fs.writeFileSync(outputPath, header + result.stepCode);

  console.log(`\n[Generator] Step definitions saved: ${outputPath}`);
  console.log(`[Generator] Generated ${missingSteps.length} new step(s)`);
  console.log(`\nNext step: npm test`);
}

main().catch((err) => {
  console.error('[Generator] Fatal error:', err);
  process.exit(1);
});
